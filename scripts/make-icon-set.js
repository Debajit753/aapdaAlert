// Builds public/js/icons.js from Material Symbols, following the UX4G design system (Government of India):
// https://www.ux4g.gov.in/foundations/iconography
//   - UX4G standardizes on Material Symbols, default style Outlined, weight 400.
//   - Filled icons are only for the active or selected item (here: the current tab in the bottom bar).
// The icons are inlined as SVG paths, so they work offline and never flash as text.
//
// To add an icon: add its name to NAMES, then run
//   npm install --no-save @material-symbols/svg-400
//   node scripts/make-icon-set.js
// Icon names: https://fonts.google.com/icons  (Apache License 2.0)
import fs from "node:fs";
import path from "node:path";

const NAMES = [
  // navigation and actions
  "home", "forum", "map", "menu_book", "menu", "close", "add", "remove", "check", "arrow_back", "chevron_right",
  "open_in_new", "refresh", "delete", "content_copy", "send", "mic", "volume_up", "photo_camera", "language", "info",
  "manage_accounts", "lock", "stop_circle", "movie", "cancel", "swap_horiz",
  // emergency
  "sos", "siren", "warning", "emergency", "call", "sms", "bolt", "flashlight_on", "sports", "campaign", "health_and_safety",
  "task_alt", "check_circle", "verified",
  // hazards
  "flood", "landslide", "earthquake", "help", "waves", "humidity_low", "humidity_mid", "humidity_high", "remove_road", "destruction",
  // people
  "person", "group", "groups", "group_add", "family_restroom", "elderly", "child_care", "pregnant_woman", "accessible",
  "personal_injury", "healing", "sentiment_satisfied", "directions_run", "block",
  // places and rescue
  "location_on", "my_location", "pin_drop", "add_location_alt", "share_location", "navigation", "explore", "camping",
  "helicopter", "directions_boat", "ambulance", "wifi_off",
  // weather, official alerts and nearby chat
  "sunny", "partly_cloudy_day", "cloud", "foggy", "rainy", "rainy_heavy", "thunderstorm", "weather_mix", "water_drop",
  "account_balance", "flag",
];

// Filled versions, used only for the active tab (UX4G rule: filled = selected state)
const FILLED = ["home", "forum", "map", "menu_book", "menu"];

const src = path.join(process.cwd(), "node_modules", "@material-symbols", "svg-400", "outlined");
const out = {};
for (const name of [...NAMES, ...FILLED.map((n) => `${n}-fill`)]) {
  const file = path.join(src, `${name}.svg`);
  if (!fs.existsSync(file)) { console.error(`Missing icon: ${name}`); process.exitCode = 1; continue; }
  const svg = fs.readFileSync(file, "utf8");
  out[name] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
}

const code = `// GENERATED by scripts/make-icon-set.js. Do not edit by hand.
// Icons: Material Symbols Outlined by Google (the UX4G standard), Apache License 2.0. https://fonts.google.com/icons
const PATHS = ${JSON.stringify(out, null, 1)};

const NS = "http://www.w3.org/2000/svg";

/** Returns an inline SVG icon element. Unknown names fall back to plain text. */
export function icon(name, cls = "") {
  if (!PATHS[name]) return document.createTextNode(name || "");
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", "0 -960 960 960");
  svg.setAttribute("class", \`ic \${cls}\`.trim());
  svg.setAttribute("aria-hidden", "true");
  const p = document.createElementNS(NS, "path");
  p.setAttribute("d", PATHS[name]);
  svg.append(p);
  return svg;
}

/** Same icon as an HTML string, for map pins. */
export function iconHtml(name, cls = "") {
  if (!PATHS[name]) return name || "";
  return \`<svg viewBox="0 -960 960 960" class="ic \${cls}" aria-hidden="true"><path d="\${PATHS[name]}"/></svg>\`;
}

/** An icon followed by text: for buttons and labels. */
export function label(name, text) {
  const span = document.createElement("span");
  span.textContent = text;
  return [icon(name), span];
}

`;
fs.writeFileSync(path.join(process.cwd(), "public", "js", "icons.js"), code);
console.log(`Wrote ${Object.keys(out).length} icons to public/js/icons.js`);
